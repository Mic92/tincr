    /// `Mode` and `Broadcast` from tinc.conf get copied. Nothing
    /// else does.
    #[test]
    fn mesh_vars_copied() {
        let cd = ConfDir::bare();
        let paths = cd.paths().clone();
        let confbase = cd.confbase();
        init_with_address(&paths, "alice", "myhost");

        let mut tc = fs::OpenOptions::new()
            .append(true)
            .open(confbase.join("tinc.conf"))
            .unwrap();
        // Mode and Broadcast → copied. Device → not copied.
        writeln!(tc, "Mode = switch").unwrap();
        writeln!(tc, "Broadcast = no").unwrap();
        writeln!(tc, "Device = /dev/net/tun").unwrap();
        drop(tc);

        let r = invite(&paths, None, "bob", SystemTime::now()).unwrap();
        let slug = r.url.rsplit('/').next().unwrap();
        let (_, cookie) = tinc_crypto::invite::parse_slug(slug).unwrap();
        let sk = keypair::read_private(&paths.invitation_key()).unwrap();
        let inv_file = paths
            .invitations_dir()
            .join(tinc_crypto::invite::cookie_filename(
                &cookie,
                sk.public_key(),
            ));
        let body = fs::read_to_string(inv_file).unwrap();

        // Chunk 1 (before separator) has Mode + Broadcast.
        let chunk1 = body.split(SEPARATOR).next().unwrap();
        assert!(chunk1.contains("Mode = switch\n"));
        assert!(chunk1.contains("Broadcast = no\n"));
        // Device is not copied. Not in the filter.
        assert!(!chunk1.contains("Device"));
    }
